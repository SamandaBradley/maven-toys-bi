--Create the database for sales and inventory project
CREATE DATABASE MavenToysDB; 

USE MavenToysDB;

--DROP DATABASE MavenToysDB;



--CREATE TABLES
CREATE TABLE PRODUCTS (
	product_ID INT  PRIMARY KEY NOT NULL, 
	product_name VARCHAR(50) NOT NULL, 
	product_category VARCHAR (50) NOT NULL,
	product_cost MONEY NOT NULL, 
	product_price MONEY NOT NULL
);

CREATE TABLE STORES (
	store_ID INT PRIMARY KEY NOT NULL, 
	store_name VARCHAR (80) NOT NULL, 
	store_city VARCHAR (50) NOT NULL, 
	store_location VARCHAR (50) NOT NULL, 
	store_open_date DATE NOT NULL
);

CREATE TABLE INVENTORY (
	store_ID INT NOT NULL, 
	product_ID INT NOT NULL, 
	stock_on_hand INT NOT NULL,
	CONSTRAINT PK_INVENTORY PRIMARY KEY (store_ID, product_ID), 
	CONSTRAINT FK_INVENTORY FOREIGN KEY (store_ID) REFERENCES STORES (store_ID),
	CONSTRAINT FK_INVENTORY1 FOREIGN KEY (product_ID) REFERENCES PRODUCTS (product_ID)
);

CREATE TABLE SALES (
	sale_id INT PRIMARY KEY NOT NULL,
	sales_dates DATE NOT NULL,
	store_ID INT NOT NULL,
	product_ID INT NOT NULL, 
	units INT NOT NULL
	CONSTRAINT FK_SALES FOREIGN KEY (store_ID) REFERENCES STORES (store_ID),
	CONSTRAINT FK_SALES1 FOREIGN KEY (product_ID) REFERENCES PRODUCTS (product_ID)
);

CREATE TABLE CALENDAR ( 
	cal_dates DATE PRIMARY KEY NOT NULL
); 


